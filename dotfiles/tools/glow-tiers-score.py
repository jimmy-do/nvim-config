#!/usr/bin/env python3
"""Regenerate lua/config/glow_tiers.lua.

  nvim --headless -c "lua vim.defer_fn(function() dofile('.../glow-tiers-measure.lua') end, 3000)"
  GLOW_OUT=/tmp/glow.json  (env for the step above)
  python3 glow-tiers-score.py /tmp/glow.json

The formula below is a transcription of the neon-bloom tap weight in
~/.config/ghostty/shaders/macbook-m4max-2056-theme-friendly-sharp.glsl.
If that shader's gates change (satGateLo/Hi, fgHueRef/Band/Soft, neonDimBoost,
neonBloom), change them here and rerun -- otherwise the tiers are stale.
"""
import json
import os
import sys

NEON = 0.60          # neonBloom
LO, HI = 0.22, 0.55  # neonBloomSatGateLo / Hi
DIM = 0.35           # neonDimBoost
FG = (0x00 / 255, 0xB0 / 255, 0x12 / 255)  # fgHueRef, tracks ghostty `foreground`
BAND, SOFT = 0.055, 0.045                  # fgHueBand / fgHueSoft

CUTS = [("neon", 0.50), ("bright", 0.38), ("soft", 0.25), ("faint", 0.12)]

# yaml VALUE tokens only, one entry per "slot"; first group present wins. Field /
# property / label groups are intentionally absent -- this measures values.
SLOTS = [
    ["@string.yaml.value", "@string.yaml", "@string", "String"],
    ["@string.yaml.quoted", "@string.yaml", "@string", "String"],
    ["@number.yaml", "@number", "Number"],
    ["@boolean.yaml", "@boolean", "Boolean"],
    ["@type.yaml.enum"],
    ["@constant.yaml.env"],
    ["@string.yaml.image"],
    ["@string.yaml.version"],
    ["@string.yaml.url"],
]


def smoothstep(a, b, x):
    t = min(max((x - a) / (b - a), 0.0), 1.0)
    return t * t * (3 - 2 * t)


def hue01(c):
    mx, mn = max(c), min(c)
    d = mx - mn
    if d <= 1e-6:
        return 0.0
    r, g, b = c
    if mx == r:
        h = ((g - b) / d) % 6
    elif mx == g:
        h = (b - r) / d + 2
    else:
        h = (r - g) / d + 4
    return (h / 6.0) % 1.0


def hue_dist(a, b):
    d = abs(a - b) % 1.0
    return min(d, 1.0 - d)


FG_HUE = hue01(FG)


def weight(hexs):
    c = (int(hexs[1:3], 16) / 255, int(hexs[3:5], 16) / 255, int(hexs[5:7], 16) / 255)
    mx, mn = max(c), min(c)
    sat = (mx - mn) / max(mx, 1e-4)
    lift = DIM * (1 - mx) * smoothstep(0.60, 0.90, sat)
    w = smoothstep(LO, HI, sat) * min(mx + lift, 1.0)
    w *= smoothstep(BAND, BAND + SOFT, hue_dist(hue01(c), FG_HUE))
    blue = min(max(c[2] - max(c[0], c[1]), 0.0), 1.0)
    w *= 1 + 0.9 * blue
    return w * NEON


def tier(score):
    for name, cut in CUTS:
        if score >= cut:
            return name
    return "flat"


def main():
    data = json.load(open(sys.argv[1]))
    scores = {}
    for entry in data:
        vals, ws = entry["vals"], []
        for slot in SLOTS:
            for group in slot:
                if group in vals:
                    ws.append(weight(vals[group]))
                    break
        if ws:
            scores[entry["name"]] = sum(ws) / len(ws)

    out = os.path.expanduser("~/.config/nvim/lua/config/glow_tiers.lua")
    with open(out, "w") as f:
        f.write(HEADER)
        for name in sorted(scores):
            f.write('  [%s] = { %s, %.3f },\n' % (json.dumps(name), json.dumps(tier(scores[name])), scores[name]))
        f.write("}\n")
    print("%d colorschemes -> %s" % (len(scores), out))


HEADER = '''-- GENERATED by dotfiles/tools/glow-tiers-score.py from a headless run of
-- dotfiles/tools/glow-tiers-measure.lua. Do not hand-edit.
--
-- Scores every installed colorscheme by how hard its yaml VALUES glow under the
-- ghostty neon bloom in
-- ~/.config/ghostty/shaders/macbook-m4max-2056-theme-friendly-sharp.glsl.
--
-- Score = mean bloom weight over the yaml VALUE tokens only (@string.yaml.value,
-- @string.yaml.quoted, numbers, booleans, @type.yaml.enum, @constant.yaml.env,
-- image/version/url). Field / property / label groups are deliberately NOT
-- counted -- this ranks the values, nothing else.
--
-- The weight is the shader's own per-tap formula:
--   sat  = (max-min)/max
--   lift = 0.35 * (1-max) * smoothstep(0.60, 0.90, sat)
--   w    = smoothstep(0.22, 0.55, sat) * min(max+lift, 1)
--   w   *= smoothstep(0.055, 0.100, hueDist(hue, hue(#00b012)))   -- fg hue kill
--   w   *= 1 + 0.9 * clamp(b - max(r,g), 0, 1)                    -- blue comp
--   w   *= 0.60                                                   -- neonBloom
-- So values sitting near the #00b012 foreground hue score ~0 however saturated
-- they are, which is what actually happens on screen.
--
-- Tiers: neon >= 0.50, bright >= 0.38, soft >= 0.25, faint >= 0.12, else flat.

return {
'''

main()
