-- ── Single source of truth for all theme transformations ─────────────────────
-- Every highlight group passes through this pipeline on each run:
--   bg:  bg_base → normalize_background → sepia → bg_contrast → bg_brightness → transparency blend
--   fg:  sepia → HSL (lightness + saturation)
--        editor_static/comment groups skip all fg transforms.
--        chrome fg/sp skips color transforms; chrome bg still uses bg knobs before chrome_darken.
--   sp:  sepia
-- transparent_bg_groups get bg blended toward TERMINAL_BG (or nil at t=1).
-- opaque_groups get bg forced to fallback_opaque_bg with blend=0.
-- All historical per-theme "manually fix tab/winbar bg" patches have been
-- removed — this pipeline handles them uniformly via transparent_bg_groups.
local function adjust_all_highlights()
  local fallback_opaque_bg = apply_background_pipeline(bg_base)

  for group, hl in pairs(get_highlights()) do
    if not hl.link then
      local adj = {}
      local changed = false

      for k, v in pairs(hl) do
        adj[k] = v
      end

      -- Pipeline per channel:
      --   bg:  bg_base → normalize_background → sepia → bg_contrast → bg_brightness → transparency
      --   fg:  sepia → fg_lightness/fg_saturation HSL
      --   sp:  sepia only
      -- Base16/TokyoNight keep native fg/sp and text attrs; backgrounds/chrome still use the global pipeline.
      local native_text_theme = preserves_native_text()
      local editor_static_fg = matches(group, editor_static_fg_groups)
      local fg_hsl_protected = matches(group, fg_hsl_protected_groups)
      -- Comments skip the ENTIRE fg pipeline (sepia + HSL lightness/saturation),
      -- so they stay at their colorscheme-native color regardless of the knobs.
      local comment_fg = matches(group, comment_protected_groups)
      local chrome_group = matches(group, chrome_groups)
      for _, key in ipairs({ "fg", "bg", "sp" }) do
        local hex = normalize_hex(adj[key])
        if hex then
          if key == "bg" then
            hex = bg_base
            adj[key] = hex
          end
          -- Same reasoning as the :FgAdjust branch further down: base16/tokyonight
          -- keep their native fg only while the knob sits NEUTRAL. Once :Sepia is
          -- set to a non-zero value the explicit knob wins, otherwise sepia would
          -- silently no-op on exactly those themes -- which is why `:Sepia 60` did
          -- nothing to yaml fields and values on storm. At the default sepia_amount=0
          -- this is identical to the old behaviour, so theme defaults are untouched.
          -- `sp` stays protected unconditionally, matching the HSL branch.
          local native_text_channel = native_text_theme
            and (key == "sp" or (key == "fg" and sepia_amount == 0))
          if key == "bg" and normalize_background ~= 0 then
            hex = normalize_bg_adjust(hex, normalize_background)
            adj[key] = hex
          end
          if
            not (
              native_text_channel
              or (chrome_group and key ~= "bg")
              or (editor_static_fg and (key == "fg" or key == "sp"))
              or (comment_fg and key == "fg")
            )
          then
            adj[key] = sepia_hex(hex, sepia_amount / 100)
          end
          if key == "bg" and bg_contrast ~= 50 then
            adj[key] = bg_contrast_adjust(adj[key], bg_contrast)
          end
          if key == "bg" and bg_brightness ~= 50 then
            if not matches(group, bg_brightness_protected_groups) then
              adj[key] = bg_brightness_adjust(adj[key], bg_brightness)
            end
          end
          -- native_text_channel is deliberately absent here: base16/tokyonight
          -- keep their native fg only while the HSL knobs sit neutral. Once
          -- :FgAdjust sets a non-50 value the explicit knob wins, otherwise it
          -- would silently no-op on exactly those themes. `sp` stays protected.
          if
            key == "fg"
            and not (chrome_group or editor_static_fg or fg_hsl_protected or comment_fg)
            and (fg_lightness ~= 50 or fg_saturation ~= 50)
          then
            -- Re-normalize: the sepia branch above is what usually converts
            -- adj[key] to a hex string, and it is skipped on native-text
            -- themes, leaving the raw integer from nvim_get_hl.
            adj[key] = adjust_fg_hsl(normalize_hex(adj[key]) or hex, fg_lightness, fg_saturation)
          end
          -- Comments are immune to every global fg knob above; comment_brightness
          -- is their one dedicated dial. Saturation is pinned at 50 (neutral) so
          -- only lightness moves — hue and chroma stay colorscheme-native.
          if key == "fg" and comment_fg and comment_brightness ~= 50 then
            adj[key] = adjust_fg_hsl(normalize_hex(adj[key]) or hex, comment_brightness, 50)
          end
          changed = true
        end
      end

      -- Strip italics globally, except Gruvbox Material Dark variants where italic syntax is part of the theme.
      -- evergarden opts in too: its comments are deliberately italic (stock, and
      -- re-asserted by apply_evergarden_comment_style). Without this line that
      -- italic is set correctly and then cleared right here, a few hundred
      -- milliseconds later -- which looks exactly like "the italic never
      -- applied". This is the ONLY place italics are turned off.
      local theme_name = vim.g.colors_name or ""
      local preserve_italics = theme_name:match("^base16%-gruvbox%-material%-dark") or theme_name == "evergarden"
      if adj.italic and not (native_text_theme or preserve_italics) then
        adj.italic = false
        changed = true
      end

      -- Transparency / chrome
      if matches(group, opaque_groups) then
        adj.bg = adj.bg or fallback_opaque_bg
        adj.blend = 0
        changed = true
      elseif chrome_group then
        -- chrome_darken picks the TONE of this surface; bg_transparency then
        -- decides how much of it survives. It used to be skipped here entirely,
        -- which is why `:BgTransparency 100` left three opaque slabs behind on
        -- an otherwise see-through editor -- the bufferline row, the statusline,
        -- and Neo-tree's title bar (all chrome groups, all still #0f0f0f).
        --
        -- Chrome takes the BASE transparency only, never the `extra` boost that
        -- Normal/LineNr/SignColumn get. That is what keeps the two knobs from
        -- collapsing into one: at the default 50 chrome is blended just 20%, so
        -- a deliberately dark tab bar (chrome_darken < 50) still reads as its
        -- own surface over a transparent buffer. Push bg_transparency to 100 and
        -- chrome dissolves with everything else.
        if adj.bg then
          if chrome_darken < 50 then
            local factor = (50 - chrome_darken) / 50
            local r, g, b = hex_to_rgb(adj.bg)
            adj.bg = rgb_to_hex(r * (1 - factor), g * (1 - factor), b * (1 - factor))
          elseif chrome_darken > 50 then
            local factor = (chrome_darken - 50) / 50
            if factor >= 1 then
              adj.bg = nil
            else
              adj.bg = blend_to_terminal(adj.bg, factor)
              adj.blend = math.floor(factor * 100 + 0.5)
            end
          end
          -- chrome_darken == 50: leave adj.bg as-is (theme default after pipeline)
        end
        if chrome_darken >= 100 then
          clear_bg_attrs(adj)
        elseif adj.bg then
          local base_transp = resolve_transparency()
          if base_transp >= 1 then
            clear_bg_attrs(adj)
          elseif base_transp > 0 then
            adj.bg = blend_to_terminal(adj.bg, base_transp)
            adj.blend = math.max(adj.blend or 0, math.floor(base_transp * 100 + 0.5))
          end
        end
        changed = true
      elseif adj.bg then
        -- Lualine pill groups (a/z): skip transparency entirely. They already
        -- have explicit theme-distinct bg colors; any blend toward terminal_bg
        -- can wash them out, especially on themes (catppuccin) where the pill
        -- bg is already close to the editor bg. Bypassing here keeps pill
        -- color identity intact across all themes.
        if matches(group, bg_brightness_protected_groups) then
          changed = true
        else
          local base_transp, extra_transp_val = resolve_transparency()
          local t = base_transp
          local is_habamax = vim.g.colors_name == "habamax"
          if matches(group, transparent_bg_groups) or (is_habamax and matches(group, habamax_extra_transparent)) then
            t = math.min(t + extra_transp_val, 1)
          end
          if t >= 1 then
            -- Fully transparent: nil out bg entirely
            clear_bg_attrs(adj)
          elseif t > 0 then
            -- Simulate gradient transparency by blending bg toward TERMINAL_BG
            adj.bg = blend_to_terminal(adj.bg, t)
            -- Also set blend for float groups that actually respect it (Pmenu border, etc.)
            adj.blend = math.max(adj.blend or 0, math.floor(t * 100 + 0.5))
          end
          changed = true
        end
      end

      if changed then
        vim.api.nvim_set_hl(0, group, adj)
      end
    end
  end

  -- Prevent Neovim's own float-level transparency from doubling up
  vim.o.winblend = 0
  vim.o.pumblend = 0

  -- Last thing in the pipeline, deliberately: it compares FINAL drawn colours,
  -- so it has to run after the loop above has re-stamped every group. See the
  -- function's header.
  fix_sigil_collision()
  apply_yaml_key_ramp()
  apply_yaml_value_style()
end

