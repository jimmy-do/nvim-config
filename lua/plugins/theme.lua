local function apply_editor_interaction_highlights()
  if preserves_native_text() then
    local function set_bg_only(group, source)
      local ok, hl = pcall(vim.api.nvim_get_hl, 0, { name = group, link = false })
      local adj = {}
      if ok and type(hl) == "table" then
        for k, v in pairs(hl) do
          adj[k] = v
        end
      end
      adj.bg = source.bg
      adj.blend = source.blend
      pcall(vim.api.nvim_set_hl, 0, group, adj)
    end
    set_bg_only("Search", EDITOR_MATCH_HIGHLIGHT)
    set_bg_only("IncSearch", EDITOR_MATCH_HIGHLIGHT)
    set_bg_only("CurSearch", EDITOR_MATCH_HIGHLIGHT)
    set_bg_only("Visual", EDITOR_VISUAL_HIGHLIGHT)
    set_bg_only("VisualNOS", EDITOR_VISUAL_HIGHLIGHT)
    return
  end
  vim.api.nvim_set_hl(0, "Search", EDITOR_MATCH_HIGHLIGHT)
  vim.api.nvim_set_hl(0, "IncSearch", EDITOR_MATCH_HIGHLIGHT)
  vim.api.nvim_set_hl(0, "CurSearch", EDITOR_MATCH_HIGHLIGHT)
  vim.api.nvim_set_hl(0, "Visual", EDITOR_VISUAL_HIGHLIGHT)
  vim.api.nvim_set_hl(0, "VisualNOS", EDITOR_VISUAL_HIGHLIGHT)
end

