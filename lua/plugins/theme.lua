-- ── Color math ───────────────────────────────────────────────────────────────
local function hex_to_rgb(hex)
  hex = hex:gsub("#", "")
  return tonumber(hex:sub(1, 2), 16), tonumber(hex:sub(3, 4), 16), tonumber(hex:sub(5, 6), 16)
end

local function clamp_color(v)
  return math.max(0, math.min(255, math.floor(v + 0.5)))
end

local function rgb_to_hex(r, g, b)
  return string.format("#%02x%02x%02x", clamp_color(r), clamp_color(g), clamp_color(b))
end

-- Bring an out-of-range triple back into 0..255 WITHOUT changing its hue.
--
-- Per-channel clamping is the trap here: it moves each channel a different
-- distance, so the ratios between them change and the hue swings. Scaling all
-- three by one factor keeps the ratios exactly, so only brightness moves.
local function fit_gamut(r, g, b)
  local max = math.max(r, g, b)
  if max > 255 then
    local k = 255 / max
    r, g, b = r * k, g * k, b * k
  end
  return r, g, b
end

-- The sepia matrix's rows sum to 1.351 / 1.203 / 0.937, so ANY light input
-- overflows: pure white maps to (344, 306, 238). Clamping that per channel
-- pinned R and G to 255 while B stayed low -- i.e. every light color came out
-- YELLOW, and the brighter it was the more yellow it got. On dracula's
-- #f8f8f2 text, `:Sepia 20` already produced #fffff0 and `:Sepia 100` #ffffe8.
-- That is the whole bug: sepia looked like a yellow wash instead of a tint.
--
-- Fixed by fitting the matrix output back into gamut FIRST, so the full-sepia
-- target is the real sepia tone (white -> #ffe3b0, the classic value), and only
-- then interpolating toward it by `amount`. Negative amounts extrapolate the
-- other way (cool) through the same fit, which is what makes -100 stay a clean
-- blue instead of clipping.
local function sepia_hex(color, amount)
  local r, g, b = hex_to_rgb(color)
  local sr, sg, sb = fit_gamut(
    r * 0.393 + g * 0.769 + b * 0.189,
    r * 0.349 + g * 0.686 + b * 0.168,
    r * 0.272 + g * 0.534 + b * 0.131
  )
  return rgb_to_hex(fit_gamut(r + (sr - r) * amount, g + (sg - g) * amount, b + (sb - b) * amount))
end

-- ── RGB ↔ HSL helpers ────────────────────────────────────────────────────────
local function rgb_to_hsl(r, g, b)
  r, g, b = r / 255, g / 255, b / 255
  local max, min = math.max(r, g, b), math.min(r, g, b)
  local l = (max + min) / 2
  local h, s = 0, 0
  if max ~= min then
    local d = max - min
    s = l > 0.5 and d / (2 - max - min) or d / (max + min)
    if max == r then
      h = (g - b) / d + (g < b and 6 or 0)
    elseif max == g then
      h = (b - r) / d + 2
    else
      h = (r - g) / d + 4
    end
    h = h / 6
  end
  return h * 360, s * 100, l * 100
end

local function hsl_to_rgb(h, s, l)
  h, s, l = h / 360, s / 100, l / 100
  local r, g, b
  if s == 0 then
    r, g, b = l, l, l
  else
    local function hue(p, q, t)
      if t < 0 then
        t = t + 1
      end
      if t > 1 then
        t = t - 1
      end
      if t < 1 / 6 then
        return p + (q - p) * 6 * t
      end
      if t < 1 / 2 then
        return q
      end
      if t < 2 / 3 then
        return p + (q - p) * (2 / 3 - t) * 6
      end
      return p
    end
    local q = l < 0.5 and l * (1 + s) or l + s - l * s
    local p = 2 * l - q
    r = hue(p, q, h + 1 / 3)
    g = hue(p, q, h)
    b = hue(p, q, h - 1 / 3)
  end
  return r * 255, g * 255, b * 255
end

local function adjust_fg_hsl(hex, lightness_level, saturation_level)
  local r, g, b = hex_to_rgb(hex)
  local h, s, l = rgb_to_hsl(r, g, b)
  -- Saturation in HSL: hue/lightness preserved, chroma scaled.
  if saturation_level ~= 50 then
    if saturation_level < 50 then
      s = s * (saturation_level / 50)
    else
      s = s + (100 - s) * ((saturation_level - 50) / 50)
    end
  end
  s = math.max(0, math.min(100, s))
  if lightness_level < 50 then
    -- Dim by scaling RGB toward black, NOT by scaling HSL lightness.
    --
    -- HSL's S is a ratio, not an amount of colour: actual chroma is
    -- S x (1 - |2L - 1|), which PEAKS at L=50. So lowering L while holding S
    -- fixed walks colours UP that curve and they get more saturated as they
    -- dim -- the opposite of dimming. Two live examples, both at `:FgAdjust 30 50`:
    --   #f8f8f2 near-white text  ->  #b3b373   a green-gold cast out of nowhere
    --                                          (S is a meaningless 30% up there)
    --   #f1fa8c dracula yellow   ->  #cfe00a   MORE neon than the original
    -- Multiplying RGB by one factor keeps every channel ratio, so hue and real
    -- chroma both survive and the colour just goes darker:
    --   #f8f8f2 -> #959591   neutral, as it should be
    --   #f1fa8c -> #919654   the same yellow, dimmer
    -- This is also what the old comment CLAIMED to do; it just used the wrong
    -- space to do it in.
    local dim = lightness_level / 50
    local dr, dg, db = hsl_to_rgb(h, s, l)
    return rgb_to_hex(dr * dim, dg * dim, db * dim)
  elseif lightness_level > 50 then
    -- Brighten toward a WARM ceiling, not pure white. Lifting HSL L all the way
    -- to 100 (the old behavior) collapses chroma — every hue converges to white
    -- — which wipes gruvbox's warm sepia cream. Cream (#ebdbb2) is already light
    -- (L≈81), so there's little headroom: we cap the lift at L=90 and boost
    -- saturation as we rise, keeping the warm tint intact. At max the cream gets
    -- brighter (e.g. ~#fff0cb) instead of washing out to #ffffff.
    local t = (lightness_level - 50) / 50 -- 0.0 (at 50) .. 1.0 (at 100)
    local l2 = l + (90 - l) * t
    if l2 < l then -- never dim in the brighten branch (cream already above 90)
      l2 = l
    end
    s = math.min(100, s * (1 + 0.8 * t))
    return rgb_to_hex(hsl_to_rgb(h, s, l2))
  end
  -- lightness_level == 50: lightness untouched (saturation may still differ).
  return rgb_to_hex(hsl_to_rgb(h, s, l))
end

-- Scale a color's HSL saturation by keep% (100 = unchanged, 0 = grayscale). Hue/Lightness preserved.
local function desaturate_hex(hex, keep)
  local r, g, b = hex_to_rgb(hex)
  local h, s, l = rgb_to_hsl(r, g, b)
  s = s * (math.max(0, math.min(100, keep)) / 100)
  return rgb_to_hex(hsl_to_rgb(h, s, l))
end

-- Scale HSL Lightness by a percentage (95 = 5% dimmer). Multiplicative, not a
-- fixed offset, so each rung of a ramp steps by the same PROPORTION of what it
-- started at instead of marching toward black at a constant rate.
local function scale_l(hex, pct)
  local r, g, b = hex_to_rgb(hex)
  local h, s, l = rgb_to_hsl(r, g, b)
  l = math.max(0, math.min(100, l * (math.max(0, pct) / 100)))
  return rgb_to_hex(hsl_to_rgb(h, s, l))
end

-- Scale saturation by a percentage, allowing values above 100 (a boost). Hue and
-- lightness are untouched; S is clamped at 100 so an already-vivid hue is a no-op.
local function scale_sat(hex, pct)
  local r, g, b = hex_to_rgb(hex)
  local h, s, l = rgb_to_hsl(r, g, b)
  s = math.max(0, math.min(100, s * (math.max(0, pct) / 100)))
  return rgb_to_hex(hsl_to_rgb(h, s, l))
end

-- Lift fg's HSL Lightness to min_lightness if below that floor; H and S unchanged.
-- bg_hex is accepted for interface consistency but lightness floor is sufficient here.
local function ensure_readable_fg(fg_hex, _bg_hex, min_lightness)
  local r, g, b = hex_to_rgb(fg_hex)
  local h, s, l = rgb_to_hsl(r, g, b)
  if l < min_lightness then
    l = min_lightness
    return rgb_to_hex(hsl_to_rgb(h, s, l))
  end
  return fg_hex
end

local function resolve_transparency()
  if bg_transparency <= 50 then
    local f = bg_transparency / 50
    return 0.20 * f, 1.00 * f
  else
    local f = (bg_transparency - 50) / 50
    return math.min(0.20 + (1.0 - 0.20) * f, 1.0), 1.0
  end
end

local function normalize_bg_adjust(hex, level)
  if level == 0 then
    return hex
  end
  local r, g, b = hex_to_rgb(hex)
  local gray = (r + g + b) / 3
  local factor = level / 100
  return rgb_to_hex(r + (gray - r) * factor, g + (gray - g) * factor, b + (gray - b) * factor)
end

local function bg_brightness_adjust(hex, level)
  if level == 50 then
    return hex
  end
  local r, g, b = hex_to_rgb(hex)
  local function adj(c, target)
    if level < 50 then
      return c * (level / 50)
    else
      return c + (target - c) * ((level - 50) / 50)
    end
  end
  return rgb_to_hex(adj(r, 0xcc), adj(g, 0xcc), adj(b, 0xcc))
end

local function bg_contrast_adjust(hex, level)
  if level == 50 then
    return hex
  end
  local r, g, b = hex_to_rgb(hex)
  local factor = math.max(0, level) / 50
  local function adj(c)
    return 128 + (c - 128) * factor
  end
  return rgb_to_hex(adj(r), adj(g), adj(b))
end

local function apply_background_pipeline(hex)
  return bg_brightness_adjust(
    bg_contrast_adjust(sepia_hex(normalize_bg_adjust(hex, normalize_background), sepia_amount / 100), bg_contrast),
    bg_brightness
  )
end

local function blend_to_terminal(hex, alpha)
  local r, g, b = hex_to_rgb(hex)
  local tr, tg, tb = hex_to_rgb(TERMINAL_BG)
  return rgb_to_hex(r + (tr - r) * alpha, g + (tg - g) * alpha, b + (tb - b) * alpha)
end

local function color_to_hex(color)
  if type(color) == "number" then
    return string.format("#%06x", color)
  end
  return color
end

local function normalize_hex(color)
  local hex = color_to_hex(color)
  if type(hex) == "string" and hex:match("^#?%x%x%x%x%x%x$") then
    return "#" .. hex:gsub("#", "")
  end
end

local function relative_luminance(hex)
  local function channel(v)
    v = v / 255
    if v <= 0.03928 then
      return v / 12.92
    end
    return ((v + 0.055) / 1.055) ^ 2.4
  end

  local r, g, b = hex_to_rgb(hex)
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
end

local function contrast_ratio(a, b)
  local la = relative_luminance(a)
  local lb = relative_luminance(b)
  if la < lb then
    la, lb = lb, la
  end
  return (la + 0.05) / (lb + 0.05)
end

local function readable_text_color(bg)
  return contrast_ratio(bg, "#000000") >= contrast_ratio(bg, "#ffffff") and "#000000" or "#ffffff"
end

