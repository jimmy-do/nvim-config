        local arg = vim.trim(opts.args)
        local cur = vim.g.theme_raw and true or false
        local want
        if arg == "on" then
          want = true
        elseif arg == "off" then
          want = false
        elseif arg == "" or arg == "toggle" then
          want = not cur
        else
          vim.notify("ThemeRaw: expected on, off or toggle", vim.log.levels.ERROR)
          return
        end
