        -- put. Matches the key ramp's call exactly.
        adj.fg = adjust_fg_hsl(hex, yaml_value_brightness, 50)
      end
    end
    pcall(vim.api.nvim_set_hl, 0, group, adj)
  end
end

-- ---------------------------------------------------------------------------
-- Sigil collision guard.
-- ---------------------------------------------------------------------------
-- `$` only works as a sigil if it is visibly NOT the colours it sits against --
-- the braces beside it and the value colours around it. Deriving it from the
-- scheme's keyword/constant hue usually lands somewhere clear, but not always:
-- in gruvbox and catppuccin the keyword hue sits right next to the image-ref
-- colour, and the `$` read as just another value.
--
-- This MUST run at the very end of adjust_all_highlights, not in
-- derive_yaml_baseline and not in apply_theme_baseline_colors. Both of those
-- run before adjust_all_highlights, which re-stamps every group from the
-- captured base -- so a correction made earlier is simply overwritten, and the
-- comparison is against pre-transform hexes that are not what gets drawn.
-- Fixing this in the wrong place is why gruvbox and catppuccin stayed broken
-- through two attempts.
--
-- A theme that hand-tunes YamlExprSigil has made a deliberate choice and is
-- skipped.
local function fix_sigil_collision()
  local baseline_key = vim.g.colors_name or ""
  if baseline_key == "kanagawa" then
    -- kanagawa sets colors_name = "kanagawa" for every variant; resolve so
    -- each variant can carry its own hand table (2026-07-27).
    local okk, kn = pcall(require, "kanagawa")
    -- _CURRENT_THEME is what :colorscheme actually loaded; config.theme is
    -- only what setup() was called with and lags behind variant switches.
    local variant = okk and (kn._CURRENT_THEME or (kn.config and kn.config.theme)) or "wave"
    baseline_key = "kanagawa-" .. variant
  end
  local baseline = load_theme_baseline_colors()[baseline_key]
  if baseline and baseline["YamlExprSigil"] then
    return
  end
  local function fg_of(group)
    local ok, hl = pcall(vim.api.nvim_get_hl, 0, { name = group, link = false })
    return (ok and hl and hl.fg) and color_to_hex(hl.fg) or nil
  end
  local sigil = fg_of("YamlExprSigil")
  if not sigil then
    return
  end
  local avoid = {
    fg_of("@string.yaml.image"),
    fg_of("@string.yaml"),
    fg_of("YamlExprBrace"),
    fg_of("YamlExprContext"),
  }
  local function min_dist(hex)
    local r1, g1, b1 = hex_to_rgb(hex)
    local worst = math.huge
    for _, o in ipairs(avoid) do
      if o then
        local r2, g2, b2 = hex_to_rgb(o)
        worst = math.min(worst, math.sqrt((r1 - r2) ^ 2 + (g1 - g2) ^ 2 + (b1 - b2) ^ 2))
      end
    end
    return worst
  end
  if min_dist(sigil) >= 60 then
    return
  end
  -- Keep the scheme's lightness so it still belongs; floor the saturation
  -- because a single character has to carry, then take the hue furthest from
  -- everything it sits beside.
  local r, g, b = hex_to_rgb(sigil)
  local h, s, l = rgb_to_hsl(r, g, b)
  s = math.max(s, 70)
  l = math.max(l, 45)
  local best, best_d = nil, -1
  for deg = 0, 345, 15 do
    local cand = rgb_to_hex(hsl_to_rgb((h + deg) % 360, s, l))
    local d = min_dist(cand)
    if d > best_d then
      best, best_d = cand, d
    end
  end
  if best then
    pcall(vim.api.nvim_set_hl, 0, "YamlExprSigil", { fg = best })
  end
end

local function capture_base()
  adjust_base_name = vim.g.colors_name or ""
  apply_theme_baseline_colors()
  adjust_base_highlights = read_highlights()
  adjust_base_editor_static_colors = {}
  adjust_base_retrobox_string_fg = nil
  if adjust_base_name == "retrobox" then
    local ok, hl = pcall(vim.api.nvim_get_hl, 0, { name = "String", link = false })
    if ok and type(hl) == "table" and hl.fg then
      adjust_base_retrobox_string_fg = color_to_hex(hl.fg)
    end
  end
  for group in pairs(adjust_base_highlights) do
    if matches(group, editor_static_fg_groups) then
      local ok, hl = pcall(vim.api.nvim_get_hl, 0, { name = group, link = false })
      if ok and type(hl) == "table" then
        local colors = {}
        if hl.fg then
          colors.fg = color_to_hex(hl.fg)
        end
        if hl.sp then
          colors.sp = color_to_hex(hl.sp)
        end
        if colors.fg or colors.sp then
          adjust_base_editor_static_colors[group] = colors
        end
      end
    end
  end
end

local function get_highlights()
  if not (adjust_base_highlights and adjust_base_name == (vim.g.colors_name or "")) then
    return read_highlights()
  end
  -- Always start from pristine cached state so every pipeline run sees original theme colors
  local merged = {}
  for k, v in pairs(adjust_base_highlights) do
    merged[k] = vim.deepcopy(v)
  end
  -- Add only groups that appeared AFTER the base was captured (plugin-injected
  -- groups). Groups already in the base keep their cached version; current
  -- modified state is ignored.
  --
  -- Newcomers are PROMOTED into the base cache the first time they are seen.
  -- Without that, a group the pipeline itself created (lualine and snacks
  -- rebuild theirs constantly, well after capture_base ran) was re-read from
  -- live state on every pass -- so each :FgAdjust re-applied the HSL transform
  -- on top of the previous result instead of recomputing from the theme color.
  -- Two or three adjustments in, those groups were saturated garbage that no
  -- further :FgAdjust could walk back, since the pristine value was gone.
  for k, v in pairs(read_highlights()) do
    if adjust_base_highlights[k] == nil then
      adjust_base_highlights[k] = vim.deepcopy(v)
      merged[k] = v
    end
  end
  return merged
end

local function apply_editor_static_colors()
  if type(adjust_base_editor_static_colors) ~= "table" then
    return
  end
  for group, colors in pairs(adjust_base_editor_static_colors) do
    -- NEVER materialize a link here. Reading with link=false RESOLVES the link
    -- into concrete values and writing that back turns a linked group into a
    -- standalone one, frozen with whatever bg its target had at this instant.
    --
    -- That is exactly how `:BgTransparency 100` left an opaque gutter behind.
    -- base16-dracula links LineNrAbove/LineNrBelow -> LineNr, so the main
    -- pipeline skips them (it only walks unlinked groups, by design). This
    -- function then resolved them, copied LineNr's pre-transparency #0f0f0f bg
    -- onto them, and pinned it there -- and because the cached base still said
    -- "link", the pipeline never came back to clear it. Every later transparency
    -- change repainted LineNr and left the two relative-number groups opaque.
    --
    -- A still-linked group needs nothing from us: it already inherits the fg we
    -- restored on its target, and it inherits the target's bg too. Skip it.
    local linked_ok, linked = pcall(vim.api.nvim_get_hl, 0, { name = group })
    if linked_ok and type(linked) == "table" and linked.link then
      goto continue
    end
    local ok, hl = pcall(vim.api.nvim_get_hl, 0, { name = group, link = false })
    local adj = {}
    if ok and type(hl) == "table" then
      for k, v in pairs(hl) do
        adj[k] = v
      end
    end
    if colors.fg then
      adj.fg = colors.fg
    end
    if colors.sp then
      adj.sp = colors.sp
    end
    pcall(vim.api.nvim_set_hl, 0, group, adj)
    ::continue::
  end
end

