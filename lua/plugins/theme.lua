        local key = current_baseline_key()
        local saved = load_saved_theme_config()
        if not saved[key] then
          vim.notify("ThemeConfigForget: nothing saved for " .. (key ~= "" and key or "?"))
          return
        end
        saved[key] = nil
        local ok, err = write_saved_theme_config(saved)
        if not ok then
          vim.notify("ThemeConfigForget failed: " .. err, vim.log.levels.ERROR)
          return
        end
        vim.notify("ThemeConfigForget: " .. key .. " dropped (reload the theme to see defaults)")
      end, { desc = "Drop this theme's saved knob config (colours are left alone)" })

      -- :ThemeRaw — session-wide bypass of the ENTIRE pipeline. While on, every
      -- theme renders bone-stock: its own background, its own palette, no bg_base
      -- stamp, no knobs, no yaml derivation, no overlays. Nothing is persisted;
      -- :ThemeRaw off (or a restart) restores the pipeline.
      vim.api.nvim_create_user_command("ThemeRaw", function(opts)
        local arg = vim.trim(opts.args)
        local cur = vim.g.theme_raw and true or false
        local want
        if arg == "on" then
          want = true
        elseif arg == "off" then
          want = false
        elseif arg == "" or arg == "toggle" then
          want = not cur
        else
          vim.notify("ThemeRaw: expected on, off or toggle", vim.log.levels.ERROR)
          return
        end
        vim.g.theme_raw = want
        -- Re-run the colorscheme: `hi clear` inside it wipes the pipeline's
        -- stamps when turning ON, and re-entering the pipeline restores them
        -- when turning OFF.
        local name = vim.g.colors_name
        if name and name ~= "" then
          pcall(vim.cmd.colorscheme, name)
        end
        -- Turning raw off while a :ThemeRawLock is held also clears the lock —
        -- otherwise the next restart silently comes back up raw.
        local unlocked = ""
        do
          local ok, state = pcall(require, "config.colorscheme_state")
          if ok and not want and state.raw_locked() then
            state.write_raw_lock(false)
            unlocked = ", lock cleared"
          end
        end
        vim.notify("ThemeRaw: " .. (want and "ON — themes render stock for this session" or "off — pipeline restored" .. unlocked))
      end, {
        nargs = "?",
        complete = function()
          return { "on", "off", "toggle" }
        end,
        desc = "Bypass the theme pipeline for the session: every theme renders stock",
      })

      -- :ThemeRawLock — :ThemeRaw that survives restarts. Same raw semantics
      -- (the ColorScheme handler's raw branch still re-applies the custom yaml
      -- capture wiring LAST, after any raw render or bg overlay), plus a marker
      -- file in stdpath("state") that options.lua reads at boot. For theme
      -- testing sessions: lock once, restart nvim as often as you like.
      vim.api.nvim_create_user_command("ThemeRawLock", function(opts)
        local ok, state = pcall(require, "config.colorscheme_state")
        if not ok then
          vim.notify("ThemeRawLock: config.colorscheme_state failed to load", vim.log.levels.ERROR)
          return
        end
        local arg = vim.trim(opts.args)
        local want
        if arg == "on" then
          want = true
        elseif arg == "off" then
          want = false
        elseif arg == "" or arg == "toggle" then
          want = not state.raw_locked()
        else
          vim.notify("ThemeRawLock: expected on, off or toggle", vim.log.levels.ERROR)
          return
        end
        state.write_raw_lock(want)
        if (vim.g.theme_raw and true or false) ~= want then
          vim.cmd("ThemeRaw " .. (want and "on" or "off"))
        end
        vim.notify("ThemeRawLock: " .. (want and "LOCKED — raw persists across restarts" or "unlocked"))
      end, {
        nargs = "?",
        complete = function()
          return { "on", "off", "toggle" }
        end,
        desc = "Persistent :ThemeRaw — raw mode survives nvim restarts until unlocked",
      })

      -- Grouped with clear=true so re-sourcing this file can't stack handlers.
      vim.api.nvim_create_autocmd("ColorScheme", {
        group = vim.api.nvim_create_augroup("ThemePipelineColorScheme", { clear = true }),
        pattern = "*",
        callback = function()
          -- Cheap preview: yaml wiring + owned bg only, no knobs, no deferred
          -- passes. The picker sets this while you scroll and clears it before
          -- applying whatever you land on. See apply_preview_background.
          if vim.g.theme_preview then
            -- Drop any deferred passes still in flight from the theme that was
            -- loaded before the picker opened: they would repaint foregrounds
            -- from the previous theme's capture over this preview.
            theme_generation = theme_generation + 1
            -- FULL baseline, not derived_only. derived_only is the :ThemeRaw
            -- contract (stock palette only, so raw stays raw); a preview wants
            -- the real yaml treatment -- the hand-tuned per-token table in
            -- theme_baseline.lua plus whatever :HlColorSave wrote. Same two
            -- calls the normal path makes (capture_base -> baseline, then the
            -- ramp at the tail of adjust_all_highlights), just without the
            -- ~35 sweeps in between.
            pcall(apply_theme_baseline_colors)
            pcall(apply_yaml_key_ramp)
            if is_storm_family() then
              pcall(apply_storm_yaml_startup_colors)
            end
            pcall(apply_preview_background)
            return
          end
          if vim.g.theme_raw then
            -- :ThemeRaw is on: leave the theme's own colours exactly as they
            -- loaded -- no bg stamp, no knobs, no overlays. The ONE thing that
            -- still runs is the yaml capture wiring: our custom queries emit
            -- token classes no colorscheme defines, so skipping the derivation
            -- flattens yaml instead of showing it stock. Derived-only (no
            -- hand-tuned table) + the key ramp, both sourced from the stock
            -- palette, so raw stays raw.
            pcall(apply_theme_baseline_colors, true)
            pcall(apply_yaml_key_ramp)
            return
          end
          local key = vim.g.colors_name or ""
          -- kanagawa.nvim sets colors_name = "kanagawa" for all variants.
          -- Resolve the actual variant via its config to get the correct lookup key.
          if key == "kanagawa" then
            local ok, kanagawa = pcall(require, "kanagawa")
            if ok and kanagawa.config and kanagawa.config.theme then
              key = "kanagawa-" .. kanagawa.config.theme
            end
          end
          if key:match("^catppuccin") then
            key = "catppuccin-mocha"
          end
          local defaults = colorscheme_defaults[key]
          -- Three layers, last one wins: hardcoded global -> hardcoded per-theme
          -- -> whatever :ThemeConfigSave wrote for this theme. Merging HERE rather
          -- than re-applying knobs on a timer is what makes a saved config exact:
          -- the values are right before the first pipeline pass runs, so there is
          -- nothing for the 700/800ms deferred passes to overwrite.
          apply_knob_defaults(
            vim.tbl_extend("force", global_theme_defaults, defaults or {}, load_saved_theme_config()[key] or {})
          )
          apply_theme_adjustments(true)
          apply_global_punct_matches()
          apply_onedark_dark_purple_overrides()
          apply_onedark_dark_helm_trim_matches()
          apply_retrobox_string_lightness()
          -- Helm template tokens ride the per-theme YamlExpr* families. Stamped
          -- twice: now, and again at 800ms behind the last deferred pipeline
          -- pass (700ms), which otherwise re-derives YamlExpr* underneath the
          -- links and leaves {{ }} on the previous theme's hues.
          apply_helm_template_links()
          vim.defer_fn(apply_helm_template_links, 800)
          -- Storm yaml fields/values: stamp the exact baseline hexes ONCE, here on
          -- the ColorScheme path only (startup / :ThemeReload / theme switch), at
          -- 800ms so it lands after the last deferred pipeline pass (700ms).
          -- Deliberately NOT inside apply_theme_adjustments -- keeping it out is what
          -- leaves :FgAdjust and friends free to move these groups afterwards.
          vim.defer_fn(apply_storm_yaml_startup_colors, 800)
        end,
      })

